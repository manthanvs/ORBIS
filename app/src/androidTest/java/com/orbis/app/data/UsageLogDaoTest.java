package com.orbis.app.data;

import static org.junit.Assert.assertEquals;

import android.content.Context;

import androidx.room.Room;
import androidx.test.ext.junit.runners.AndroidJUnit4;
import androidx.test.platform.app.InstrumentationRegistry;

import com.orbis.app.LiveDataValue;

import org.junit.After;
import org.junit.Before;
import org.junit.Test;
import org.junit.runner.RunWith;

import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;

@RunWith(AndroidJUnit4.class)
public class UsageLogDaoTest {

    private OrbisDatabase database;
    private UsageLogDao dao;

    private static UsageLog log(String app, String date, long durationMillis) {
        return new UsageLog(0L, app, date, durationMillis);
    }

    @Before
    public void setUp() {
        Context context = InstrumentationRegistry.getInstrumentation().getTargetContext();
        database = Room.inMemoryDatabaseBuilder(context, OrbisDatabase.class).build();
        dao = database.usageLogDao();
    }

    @After
    public void tearDown() {
        database.close();
    }

    @Test
    public void refreshingTheSameDayReplacesRatherThanDuplicates() throws InterruptedException {
        // Guards the unique (app, date) index. Without it, REPLACE has only the
        // autogenerated id to match on and every refresh appends a new row.
        dao.upsert(log("com.instagram.android", "2026-07-29", 60_000L));
        dao.upsert(log("com.instagram.android", "2026-07-29", 90_000L));

        List<UsageLog> rows = LiveDataValue.of(dao.observeForDate("2026-07-29"));

        assertEquals(1, rows.size());
        assertEquals(90_000L, rows.get(0).durationMillis);
    }

    @Test
    public void sameAppOnDifferentDaysKeepsSeparateRows() throws InterruptedException {
        dao.upsert(log("com.instagram.android", "2026-07-28", 60_000L));
        dao.upsert(log("com.instagram.android", "2026-07-29", 30_000L));

        assertEquals(1, LiveDataValue.of(dao.observeForDate("2026-07-28")).size());
        assertEquals(1, LiveDataValue.of(dao.observeForDate("2026-07-29")).size());
    }

    @Test
    public void observeForDateOrdersByDurationDescending() throws InterruptedException {
        dao.upsert(log("com.whatsapp", "2026-07-29", 10_000L));
        dao.upsert(log("com.instagram.android", "2026-07-29", 99_000L));
        dao.upsert(log("com.snapchat.android", "2026-07-29", 50_000L));

        List<String> apps = new ArrayList<>();
        for (UsageLog row : LiveDataValue.of(dao.observeForDate("2026-07-29"))) {
            apps.add(row.app);
        }

        assertEquals(
                Arrays.asList(
                        "com.instagram.android", "com.snapchat.android", "com.whatsapp"),
                apps);
    }

    @Test
    public void forDateRangeSpansInclusiveBounds() {
        dao.upsert(log("com.instagram.android", "2026-07-27", 1_000L));
        dao.upsert(log("com.instagram.android", "2026-07-28", 2_000L));
        dao.upsert(log("com.instagram.android", "2026-07-29", 3_000L));

        List<UsageLog> inRange = dao.forDateRange("2026-07-27", "2026-07-28");

        long total = 0L;
        for (UsageLog row : inRange) {
            total += row.durationMillis;
        }

        assertEquals(2, inRange.size());
        assertEquals(3_000L, total);
    }
}
